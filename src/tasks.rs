//! stomp's own Slurm work, called tasks (§14).
//!
//! Each task has a directory under `tasks/` holding its generated sbatch
//! script, Slurm's output, a `state.json` and, while it runs, `progress.json`.
//! Tasks never write the catalog; they report through these files and the inbox.

use std::collections::HashMap;
use std::io::Write as _;
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};

use crate::config::Config;
use crate::paths;

/// How many times an interrupted task resubmits itself.
pub const MAX_RESUBMITS: u32 = 5;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Status {
    Submitted,
    Running,
    /// Stopped early and not resubmitted; its saved progress can be resumed.
    Incomplete,
    Done,
    /// Finished, but left some things undone on purpose (a restore that
    /// didn't replace existing files); the message says what.
    Partial,
    Failed,
    Cancelled,
}

impl Status {
    pub fn label(self) -> &'static str {
        match self {
            Status::Submitted => "submitted",
            Status::Running => "running",
            Status::Incomplete => "incomplete",
            Status::Done => "done",
            Status::Partial => "partial",
            Status::Failed => "failed",
            Status::Cancelled => "cancelled",
        }
    }

    pub fn is_final(self) -> bool {
        matches!(
            self,
            Status::Done | Status::Partial | Status::Failed | Status::Cancelled
        )
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskState {
    pub id: String,
    pub kind: String,
    pub status: Status,
    /// Every Slurm job this task has run as, oldest first.
    pub slurm_jobs: Vec<String>,
    pub resubmits: u32,
    pub created_at: String,
    pub updated_at: String,
    pub message: Option<String>,
}

/// Per-command overrides of the `[slurm]` settings (§14.2).
#[derive(Debug, Clone, Default)]
pub struct Overrides {
    pub time: Option<String>,
    pub cpus: Option<u32>,
    pub mem: Option<String>,
    pub partition: Option<String>,
    pub account: Option<String>,
}

pub fn tasks_dir(data_dir: &Path) -> PathBuf {
    data_dir.join("tasks")
}

pub fn task_dir(data_dir: &Path, id: &str) -> PathBuf {
    tasks_dir(data_dir).join(id)
}

pub fn progress_path(data_dir: &Path, id: &str) -> PathBuf {
    task_dir(data_dir, id).join("progress.json")
}

fn new_id(kind: &str) -> String {
    let now = jiff::Timestamp::now();
    // Local time, like every other time stomp shows.
    let stamp = now
        .to_zoned_datetime(jiff::tz::TimeZone::system())
        .strftime("%Y%m%d-%H%M%S")
        .to_string();
    format!(
        "{kind}-{stamp}-{:04x}",
        (now.subsec_nanosecond() as u32 ^ std::process::id()) & 0xffff
    )
}

/// Quotes a string for a POSIX shell.
fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// The sbatch script for a task.
pub fn render_script(
    cfg: &Config,
    overrides: &Overrides,
    dir: &Path,
    kind: &str,
    exe: &Path,
    config_path: &Path,
    args: &[String],
) -> String {
    let slurm = &cfg.slurm;
    let mut lines = vec![
        "#!/bin/bash".to_string(),
        format!("#SBATCH --job-name=stomp-{kind}"),
        format!("#SBATCH --output={}/slurm-%j.out", dir.display()),
        // Five minutes' warning before the time limit, so the task can save its progress.
        "#SBATCH --signal=B:USR1@300".to_string(),
    ];
    let cpus = overrides
        .cpus
        .or(slurm.cpus)
        .unwrap_or(cfg.scan.max_threads as u32);
    lines.push(format!("#SBATCH --cpus-per-task={cpus}"));
    let optional = [
        ("time", overrides.time.as_ref().or(slurm.time.as_ref())),
        ("mem", overrides.mem.as_ref().or(slurm.mem.as_ref())),
        (
            "partition",
            overrides.partition.as_ref().or(slurm.partition.as_ref()),
        ),
        (
            "account",
            overrides.account.as_ref().or(slurm.account.as_ref()),
        ),
    ];
    for (option, value) in optional {
        if let Some(value) = value {
            lines.push(format!("#SBATCH --{option}={value}"));
        }
    }
    let mut command = vec![
        sh_quote(&exe.to_string_lossy()),
        "--config".to_string(),
        sh_quote(&config_path.to_string_lossy()),
    ];
    command.extend(args.iter().map(|a| sh_quote(a)));
    lines.extend([
        String::new(),
        "# Generated by stomp. To run it again: sbatch <this file>".to_string(),
        format!("exec {}", command.join(" ")),
        String::new(),
    ]);
    lines.join("\n")
}

fn sbatch(script: &Path) -> Result<String> {
    let output = Command::new("sbatch")
        .arg("--parsable")
        .arg(script)
        .output()
        .context("cannot run sbatch; is Slurm available here?")?;
    if !output.status.success() {
        bail!(
            "sbatch failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    let text = String::from_utf8_lossy(&output.stdout);
    // `--parsable` prints "<job id>" or "<job id>;<cluster>".
    let job = text
        .trim()
        .split(';')
        .next()
        .unwrap_or_default()
        .to_string();
    if job.is_empty() {
        bail!("sbatch did not print a job ID");
    }
    Ok(job)
}

/// Creates a task and submits it. `args` are stomp's arguments, without `--task`.
pub fn submit(
    cfg: &Config,
    config_path: &Path,
    data_dir: &Path,
    kind: &str,
    args: &[String],
    overrides: &Overrides,
) -> Result<TaskState> {
    let id = new_id(kind);
    let dir = task_dir(data_dir, &id);
    paths::create_private_dir(&dir)?;
    let exe = std::env::current_exe().context("cannot find the stomp executable")?;
    let config_path = std::fs::canonicalize(config_path).unwrap_or(config_path.to_path_buf());
    let mut task_args = args.to_vec();
    task_args.extend(["--task".to_string(), id.clone()]);
    let script = render_script(cfg, overrides, &dir, kind, &exe, &config_path, &task_args);
    let script_path = dir.join("task.sh");
    std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o700)
        .open(&script_path)?
        .write_all(script.as_bytes())?;

    let job = sbatch(&script_path)?;
    let now = jiff::Timestamp::now().to_string();
    let state = TaskState {
        id,
        kind: kind.to_string(),
        status: Status::Submitted,
        slurm_jobs: vec![job],
        resubmits: 0,
        created_at: now.clone(),
        updated_at: now,
        message: None,
    };
    save(data_dir, &state)?;
    Ok(state)
}

/// Submits a task's script again, to continue where it stopped.
pub fn resubmit(data_dir: &Path, state: &mut TaskState) -> Result<String> {
    let job = sbatch(&task_dir(data_dir, &state.id).join("task.sh"))?;
    state.slurm_jobs.push(job.clone());
    state.resubmits += 1;
    state.status = Status::Submitted;
    state.updated_at = jiff::Timestamp::now().to_string();
    save(data_dir, state)?;
    Ok(job)
}

pub fn load(data_dir: &Path, id: &str) -> Result<TaskState> {
    let path = task_dir(data_dir, id).join("state.json");
    let text = std::fs::read_to_string(&path).with_context(|| format!("no task {id:?}"))?;
    Ok(serde_json::from_str(&text)?)
}

/// Writes a task's state atomically.
pub fn save(data_dir: &Path, state: &TaskState) -> Result<()> {
    let dir = task_dir(data_dir, &state.id);
    let tmp = dir.join(format!(".state.{}.tmp", std::process::id()));
    std::fs::write(&tmp, serde_json::to_string_pretty(state)?)?;
    std::fs::rename(&tmp, dir.join("state.json"))?;
    Ok(())
}

/// Loads, changes and saves a task's state.
pub fn update(data_dir: &Path, id: &str, change: impl FnOnce(&mut TaskState)) -> Result<TaskState> {
    let mut state = load(data_dir, id)?;
    change(&mut state);
    state.updated_at = jiff::Timestamp::now().to_string();
    save(data_dir, &state)?;
    Ok(state)
}

/// All tasks, oldest first.
pub fn list(data_dir: &Path) -> Result<Vec<TaskState>> {
    let entries = match std::fs::read_dir(tasks_dir(data_dir)) {
        Ok(entries) => entries,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(e.into()),
    };
    let mut tasks: Vec<TaskState> = entries
        .filter_map(Result::ok)
        .filter_map(|e| load(data_dir, &e.file_name().to_string_lossy()).ok())
        .collect();
    tasks.sort_by(|a, b| a.created_at.cmp(&b.created_at));
    Ok(tasks)
}

/// Queue states (e.g. `PENDING`, `RUNNING`) for jobs still in the queue.
pub fn queue_states(jobs: &[String]) -> HashMap<String, String> {
    if jobs.is_empty() || crate::sys::which("squeue").is_none() {
        return HashMap::new();
    }
    let Ok(output) = Command::new("squeue")
        .args(["-h", "-o", "%i %T", "-j", &jobs.join(",")])
        .output()
    else {
        return HashMap::new();
    };
    String::from_utf8_lossy(&output.stdout)
        .lines()
        .filter_map(|l| l.split_once(' '))
        .map(|(id, state)| (id.to_string(), state.trim().to_string()))
        .collect()
}

/// An unfinished task of `kind` whose job script mentions `needle` (such as
/// an archive ID) and whose Slurm job is still queued or running.
pub fn active_for(data_dir: &Path, kind: &str, needle: &str) -> Option<TaskState> {
    let candidates: Vec<TaskState> = list(data_dir)
        .ok()?
        .into_iter()
        .filter(|t| {
            t.kind == kind
                && !t.status.is_final()
                && std::fs::read_to_string(task_dir(data_dir, &t.id).join("task.sh"))
                    .is_ok_and(|script| script.contains(needle))
        })
        .collect();
    if candidates.is_empty() {
        return None;
    }
    if crate::sys::which("squeue").is_none() {
        // Can't ask Slurm; trust what the task last recorded.
        return candidates
            .into_iter()
            .find(|t| matches!(t.status, Status::Submitted | Status::Running));
    }
    let jobs: Vec<String> = candidates
        .iter()
        .filter_map(|t| t.slurm_jobs.last().cloned())
        .collect();
    let queued = queue_states(&jobs);
    candidates
        .into_iter()
        .find(|t| t.slurm_jobs.last().is_some_and(|j| queued.contains_key(j)))
}

/// Cancels a task's current Slurm job.
pub fn cancel(data_dir: &Path, id: &str) -> Result<TaskState> {
    let state = load(data_dir, id)?;
    if state.status.is_final() {
        bail!("task {id} is already {}", state.status.label());
    }
    // Marked first, so a task stopping on the signal sees it and doesn't
    // resubmit itself.
    let before = state.status;
    let state = update(data_dir, id, |s| s.status = Status::Cancelled)?;
    if let Some(job) = state.slurm_jobs.last() {
        let output = Command::new("scancel").arg(job).output();
        let failure = match output {
            Ok(o) if o.status.success() => None,
            Ok(o) => Some(format!(
                "scancel failed: {}",
                String::from_utf8_lossy(&o.stderr).trim()
            )),
            Err(e) => Some(format!("cannot run scancel: {e}")),
        };
        if let Some(why) = failure {
            update(data_dir, id, |s| s.status = before)?;
            bail!(why);
        }
    }
    Ok(state)
}

/// Whether a task that stopped early should resubmit itself: only when
/// Slurm warned of its time limit, it wasn't cancelled, and resubmitting is
/// on and not used up.
pub fn should_resubmit(cfg: &crate::config::Config, state: &TaskState, time_limit: bool) -> bool {
    time_limit
        && state.status != Status::Cancelled
        && cfg.slurm.auto_resubmit.unwrap_or(true)
        && state.resubmits < MAX_RESUBMITS
}

/// The arguments a task's job script passes to stomp, after `--config FILE`.
pub fn script_args(data_dir: &Path, id: &str) -> Vec<String> {
    let Ok(script) = std::fs::read_to_string(task_dir(data_dir, id).join("task.sh")) else {
        return Vec::new();
    };
    let Some(line) = script.lines().find(|l| l.starts_with("exec ")) else {
        return Vec::new();
    };
    // Every word is single-quoted, with ' written as '\''.
    let mut words = Vec::new();
    let mut rest = line;
    while let Some(start) = rest.find('\'') {
        let mut word = String::new();
        let mut tail = &rest[start + 1..];
        loop {
            let Some(end) = tail.find('\'') else {
                return Vec::new();
            };
            word.push_str(&tail[..end]);
            tail = &tail[end + 1..];
            match tail.strip_prefix("\\''") {
                Some(more) => {
                    word.push('\'');
                    tail = more;
                }
                None => break,
            }
        }
        words.push(word);
        rest = tail;
    }
    // The quoted words are [exe, config file, args...]; `--config` itself isn't quoted.
    words.into_iter().skip(2).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_a_scripts_arguments_back() {
        let tmp = tempfile::tempdir().unwrap();
        let dir = task_dir(tmp.path(), "archive-1");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            dir.join("task.sh"),
            "#!/bin/bash\nexec '/u/bin/stomp' --config '/u/c.toml' 'archive' '/u/it'\\''s here' '--yes'\n",
        )
        .unwrap();
        assert_eq!(
            script_args(tmp.path(), "archive-1"),
            ["archive", "/u/it's here", "--yes"]
        );
        assert!(script_args(tmp.path(), "nope").is_empty());
    }

    #[test]
    fn renders_script_with_overrides_and_quoting() {
        let tmp = tempfile::tempdir().unwrap();
        let text = format!(
            "general.roots = [\"{}\"]\n[slurm]\naccount = \"lab\"\ntime = \"02:00:00\"\n",
            tmp.path().display()
        );
        let cfg = Config::parse(&text, Path::new("t.toml")).unwrap();
        let overrides = Overrides {
            time: Some("12:00:00".into()),
            cpus: Some(4),
            ..Overrides::default()
        };
        let script = render_script(
            &cfg,
            &overrides,
            Path::new("/data/tasks/scan-1"),
            "scan",
            Path::new("/home/u/bin/stomp"),
            Path::new("/home/u/it's.toml"),
            &["scan".into(), "--task".into(), "scan-1".into()],
        );
        assert!(script.contains("#SBATCH --signal=B:USR1@300\n"));
        assert!(script.contains("#SBATCH --cpus-per-task=4\n"));
        assert!(script.contains("#SBATCH --time=12:00:00\n"));
        assert!(script.contains("#SBATCH --account=lab\n"));
        assert!(!script.contains("--partition"));
        assert!(script.contains(
            "exec '/home/u/bin/stomp' --config '/home/u/it'\\''s.toml' 'scan' '--task' 'scan-1'"
        ));
    }

    #[test]
    fn saves_and_lists_state() {
        let tmp = tempfile::tempdir().unwrap();
        let data = tmp.path();
        let state = TaskState {
            id: "scan-x".into(),
            kind: "scan".into(),
            status: Status::Submitted,
            slurm_jobs: vec!["5".into()],
            resubmits: 0,
            created_at: "2026-11-17T00:00:00Z".into(),
            updated_at: "2026-11-17T00:00:00Z".into(),
            message: None,
        };
        paths::create_private_dir(&task_dir(data, "scan-x")).unwrap();
        save(data, &state).unwrap();
        let updated = update(data, "scan-x", |s| s.status = Status::Done).unwrap();
        assert_eq!(updated.status, Status::Done);
        assert_eq!(list(data).unwrap().len(), 1);
        assert!(cancel(data, "scan-x").is_err()); // already finished
    }
}
